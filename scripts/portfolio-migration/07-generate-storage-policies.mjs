#!/usr/bin/env node
/**
 * Phase 5 storage policy generator (D-01, D-03).
 *
 * Usage:
 *   node scripts/portfolio-migration/07-generate-storage-policies.mjs --generate --source-ref <ziko>
 *        [--map-out <path>] [--sql-out <path>]
 *   node scripts/portfolio-migration/07-generate-storage-policies.mjs --check --source-ref <ziko>
 *        [--map-out <path>] [--sql-out <path>]
 *   node scripts/portfolio-migration/07-generate-storage-policies.mjs --apply --project-ref <scratch|portfolio>
 *        [--confirm-ref <ref>] [--sql <path>]
 *
 * --generate / --check only read ziko (storage.buckets, pg_policies). --apply is the only write path and is
 * guarded by assertWriteAllowed. Console output is limited to names and counts.
 * Exit codes: 0 ok; 1 failed/drift/refused; 2 bad arguments; 3 policy apply not permitted for the CLI role.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PROJECTS, parseCliArgs, assertWriteAllowed, runSql, redactPii, isMain } from '../auth-merge/lib.mjs';
import { loadRenameMap } from './lib-data.mjs';
import { buildBucketMap, rewritePolicy, renderPoliciesSql, findStalePolicyRefs } from './lib-storage.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DEFAULT_MAP = join(__dirname, 'bucket-map.generated.json');
const DEFAULT_SQL = join(__dirname, '..', '..', 'supabase', 'portfolio-migrations', '20261002160000_portfolio_ziko_storage_policies.sql');

const BUCKETS_SQL = 'SELECT id, public, file_size_limit, allowed_mime_types FROM storage.buckets ORDER BY id';
const POLICIES_SQL = "SELECT policyname, cmd, roles::text AS roles, permissive, qual, with_check FROM pg_policies WHERE schemaname = 'storage' AND tablename = 'objects' ORDER BY policyname";
const ZIKO_COUNT_SQL = "SELECT count(*)::int AS n FROM pg_policies WHERE schemaname='storage' AND tablename='objects' AND policyname LIKE 'ziko\\_%'";
const COUNT_RE = /^-- expected policy count: (\d+)$/m;

const HELP = `07-generate-storage-policies.mjs - Phase 5 bucket map and storage policies

  --generate --source-ref <ziko>    Read ziko, write bucket map + policies migration.
  --check    --source-ref <ziko>    Regenerate in memory, fail on drift or stale references.
  --apply    --project-ref <ref>    Execute the committed migration (scratch; portfolio needs --confirm-ref).
Optional: --map-out <path> --sql-out <path> --sql <path> --confirm-ref <ref> --help
Exit codes: 0 ok; 1 failed; 2 bad arguments; 3 apply not permitted.
`;

export class UsageError extends Error {}

export function resolveRun(args) {
  const { generate, check, apply, sourceRef, projectRef, confirmRef } = args ?? {};
  const modes = [generate && 'generate', check && 'check', apply && 'apply'].filter(Boolean);
  if (modes.length !== 1) throw new UsageError('exactly one of --generate | --check | --apply is required');
  const mode = modes[0];
  if (mode !== 'apply') {
    if (sourceRef !== PROJECTS.ziko) throw new UsageError('--source-ref must be the ziko project ref');
    return { mode };
  }
  if (!projectRef) throw new UsageError('--project-ref is required for --apply');
  if (projectRef === PROJECTS.ziko) throw new UsageError('ziko is the source and is never an apply target');
  if (projectRef === PROJECTS.portfolio && confirmRef !== PROJECTS.portfolio) {
    throw new UsageError('portfolio requires --confirm-ref equal to the portfolio ref');
  }
  return { mode, projectRef, confirmRef: confirmRef ?? null };
}

/** { is_coach_of: 'ziko_is_coach_of', ... } from the signature-keyed map.functions. */
export function deriveFunctionRenames(renameMap) {
  const out = {};
  for (const [oldSig, newSig] of Object.entries(renameMap?.functions ?? {})) {
    out[oldSig.split('(')[0].trim()] = String(newSig).split('(')[0].trim();
  }
  return out;
}

export function buildMigration(bucketRows, policyRows, renames) {
  const bucketIds = bucketRows.map((b) => b.id);
  const rewritten = policyRows.map((p) => rewritePolicy(p, { bucketIds, functionRenames: renames }));
  const stale = findStalePolicyRefs(rewritten, { bucketIds, functionNames: Object.keys(renames) });
  if (stale.length) throw new Error(`stale references after rewrite in ${stale.length} policies`);
  const body = renderPoliciesSql(rewritten, {
    header: 'Phase 5 storage policies for ziko- buckets (D-03). Generated by 07-generate-storage-policies.mjs from live ziko metadata.',
  });
  const lines = body.trimEnd().split('\n');
  // lines[0..1] are comment headers, lines[2] is blank, policies follow
  const head = lines.slice(0, 2).concat(`-- expected policy count: ${rewritten.length}`, '', 'BEGIN;', '');
  return `${head.concat(lines.slice(3)).join('\n')}\n\nCOMMIT;\n`;
}

/** Static stale-reference grep over a migration file. Returns offender descriptions. */
export function staleCheckFile(sqlText, bucketIds, functionNames = ['is_coach_of']) {
  const code = String(sqlText)
    .split('\n')
    .filter((l) => !l.trim().startsWith('--'))
    .join('\n');
  const hit = findStalePolicyRefs([{ name: 'file', qual: code, with_check: '' }], { bucketIds, functionNames });
  return hit.length ? ['file contains bare bucket ids or unprefixed function calls'] : [];
}

async function readLive(source) {
  const buckets = await runSql(source, BUCKETS_SQL);
  const policies = await runSql(source, POLICIES_SQL);
  return { buckets, policies };
}

async function renames() {
  return deriveFunctionRenames(await loadRenameMap());
}

function stableMap(map) {
  return JSON.stringify({ ...map, generated_at: null }, null, 2);
}

async function generate(args) {
  const { buckets, policies } = await readLive(PROJECTS.ziko);
  const map = buildBucketMap(buckets, { sourceRef: PROJECTS.ziko, generatedAt: new Date().toISOString() });
  const sql = buildMigration(buckets, policies, await renames());
  await writeFile(args.mapOut ?? DEFAULT_MAP, `${JSON.stringify(map, null, 2)}\n`, 'utf8');
  await writeFile(args.sqlOut ?? DEFAULT_SQL, sql, 'utf8');
  console.log(`generated: ${map.buckets.length} buckets, ${policies.length} policies`);
  return 0;
}

async function check(args) {
  const { buckets, policies } = await readLive(PROJECTS.ziko);
  const problems = [];
  const sqlPath = args.sqlOut ?? DEFAULT_SQL;
  const mapPath = args.mapOut ?? DEFAULT_MAP;
  const expectedSql = buildMigration(buckets, policies, await renames());
  const committedSql = await readFile(sqlPath, 'utf8');
  const names = (t) => [...t.matchAll(/^CREATE POLICY "([^"]+)"/gm)].map((m) => m[1]);
  if (committedSql.replace(/\r\n/g, '\n') !== expectedSql) {
    const a = new Set(names(committedSql));
    const b = new Set(names(expectedSql));
    const diff = [...new Set([...a].filter((n) => !b.has(n)).concat([...b].filter((n) => !a.has(n))))];
    problems.push(`policies migration drift (name differences: ${diff.length ? diff.join(', ') : 'none, definitions differ'})`);
  }
  const expectedMap = buildBucketMap(buckets, { sourceRef: PROJECTS.ziko, generatedAt: null });
  const committedMap = JSON.parse(await readFile(mapPath, 'utf8'));
  if (stableMap(committedMap) !== stableMap(expectedMap)) {
    const a = new Set(committedMap.buckets.map((x) => x.id));
    const b = new Set(expectedMap.buckets.map((x) => x.id));
    const diff = [...a].filter((n) => !b.has(n)).concat([...b].filter((n) => !a.has(n)));
    problems.push(`bucket map drift (id differences: ${diff.length ? diff.join(', ') : 'none, config differs'})`);
  }
  const stale = staleCheckFile(committedSql, buckets.map((b) => b.id), Object.keys(await renames()));
  problems.push(...stale);
  if (problems.length) {
    for (const p of problems) console.error(`FAIL: ${p}`);
    return 1;
  }
  console.log(`check ok: ${buckets.length} buckets, ${policies.length} policies, 0 stale references`);
  return 0;
}

async function apply(run, args) {
  assertWriteAllowed({ projectRef: run.projectRef, confirmRef: run.confirmRef });
  const sqlPath = args.sql ?? DEFAULT_SQL;
  const sql = await readFile(sqlPath, 'utf8');
  const map = JSON.parse(await readFile(args.mapOut ?? DEFAULT_MAP, 'utf8'));
  const stale = staleCheckFile(sql, map.buckets.map((b) => b.id));
  if (stale.length) {
    console.error(`FAIL: ${stale.join('; ')}`);
    return 1;
  }
  const m = COUNT_RE.exec(sql);
  if (!m) {
    console.error('FAIL: migration header has no expected policy count');
    return 1;
  }
  const expected = Number(m[1]);
  try {
    await runSql(run.projectRef, sql);
  } catch (err) {
    const msg = redactPii(String(err.message));
    console.error(msg.slice(0, 400));
    if (/permission|must be owner|not permitted|denied/i.test(msg)) {
      console.error('policy apply not permitted for the CLI role - see RESEARCH A1');
      return 3;
    }
    return 1;
  }
  const rows = await runSql(run.projectRef, ZIKO_COUNT_SQL);
  const n = Number(rows[0]?.n);
  if (n !== expected) {
    console.error(`FAIL: ${n} ziko_ policies present, expected ${expected}`);
    return 1;
  }
  console.log(`applied: ${n} ziko_ storage policies on target`);
  return 0;
}

async function main() {
  const args = parseCliArgs(process.argv.slice(2), {
    generate: 'boolean',
    check: 'boolean',
    apply: 'boolean',
    'source-ref': 'string',
    'project-ref': 'string',
    'confirm-ref': 'string',
    'map-out': 'string',
    'sql-out': 'string',
    sql: 'string',
  });
  if (args.help) {
    console.log(HELP);
    return 0;
  }
  let run;
  try {
    run = resolveRun(args);
  } catch (err) {
    if (err instanceof UsageError) {
      console.error(`ERROR: ${err.message}\n\n${HELP}`);
      return 2;
    }
    throw err;
  }
  if (run.mode === 'generate') return generate(args);
  if (run.mode === 'check') return check(args);
  return apply(run, args);
}

if (isMain(import.meta.url)) {
  main().then(
    (code) => process.exit(code),
    (err) => {
      console.error(redactPii(String(err.message ?? err)).slice(0, 400));
      process.exit(1);
    },
  );
}
